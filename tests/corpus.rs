use lojban::grammar::{LojbanParser, Rule};
use pest::Parser;

/// 既知の未対応・非標準文(解析に失敗することが正)
const KNOWN_FAILURES: &[&str] = &[
    // 非標準形の借用語(zantufa でも受理されない)
    "rutrpinia",
    "rutrxanonaskuamosa",
];

#[test]
fn 既知の失敗例は拒否される() {
    for s in KNOWN_FAILURES {
        assert!(
            LojbanParser::parse(Rule::text, s).is_err(),
            "既知の失敗例が受理された: {s}"
        );
    }
}

